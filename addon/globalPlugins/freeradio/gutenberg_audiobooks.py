# -*- coding: utf-8 -*-
# FreeRadio - Audio Books (Project Gutenberg Open Audiobook Collection) integration
#
# Searches and resolves playable media from The Project Gutenberg Open
# Audiobook Collection (https://marhamilresearch4.blob.core.windows.net/
# gutenberg-public/Website/index.html) - several thousand public-domain
# books from Project Gutenberg (https://www.gutenberg.org/), narrated
# end-to-end by Microsoft's neural text-to-speech and produced as part of
# a Project Gutenberg/Microsoft/MIT collaboration (see their Interspeech
# 2023 paper, "Large-Scale Automatic Audiobook Creation",
# https://arxiv.org/abs/2309.03926). Every title in the collection is
# machine-narrated, not read by a human - see GutenbergAudiobook.narrator
# below, which says so plainly rather than leaving it blank, since that's
# exactly the kind of thing a listener choosing a book wants to know
# upfront.
#
# WHY ARCHIVE.ORG: the collection's own site (linked above) only offers a
# single flat, unpaginated "browse all ~5000 titles" HTML page with no
# search and no per-book API of its own - not something this module can
# usefully query. Its "Listen" section, however, links the collection's
# archive.org mirror: every book is also its own archive.org item. That
# gives this module the exact same two well-documented, unauthenticated
# JSON endpoints librivox.py already relies on for the same reason (see
# that module's docstring) - advancedsearch.php for search and
# metadata/<identifier> for a book's file listing - so this module mirrors
# librivox.py's structure closely: same GutenbergAudiobook/GutenbergLibrary
# shape as LibrivoxBook/LibrivoxLibrary (attribute- and method-compatible
# with GetemBook, so radioDialog.py's Audio Books tab drives all three
# sources through the same generic code - see
# RadioDialog._audiobook_module_for()/_audiobook_library_for()), same
# _fetch()/_first_str()/_strip_html() helpers, same archive.org
# details-URL handling.
#
# CONFIRMED AGAINST A REAL ITEM: unlike this module's first draft (which
# guessed at the uploader field and the file-format label without being
# able to reach archive.org from the environment it was authored in -
# and got the uploader-field guess wrong, per a real "no results" search
# reported back), this version is checked against an actual item's own
# metadata page (archive.org/details/synapseml_gutenberg_life_in_mexico_by_madame_calderon_de_la):
#   - Every book carries the collection tag "gutenberg-audiobooks" (shown
#     on the item page under "IN COLLECTIONS" as "Project Gutenberg
#     Audiobook Collection") - COLLECTION below - which is what
#     search_gutenberg_audiobooks() filters on, the same way
#     librivox.search_librivox() filters on "librivoxaudio". This is
#     what the first draft's "uploader:" filter should have been -
#     archive.org's search index apparently doesn't expose that item's
#     uploader field in a form advancedsearch.php's uploader: query
#     matches, even though the item page itself does show "Uploaded by
#     The Project Gutenberg Open Audiobook Collection".
#   - The audio file's format label is the bare string "MP3" (not "VBR
#     MP3" or "64Kbps MP3", either of which would have kept silently
#     matching nothing) - now _AUDIO_FORMAT_CANDIDATES' first and
#     primary entry, with the other two labels kept as fallbacks in case
#     some items in this ~5000-title collection were produced
#     differently, and a bare ".mp3"-extension match kept as a last
#     resort after that.
#   - Each item also carries "tts-voice" (e.g. "SteffanNeural" on the
#     item checked) - the specific Azure neural voice used - surfaced in
#     GutenbergAudiobook.narrator when present, for a more specific
#     credit than the generic AI-narration label alone.
# What's still an extrapolation rather than a directly confirmed fact:
# that every one of the ~5000 items in this collection was produced and
# tagged identically to the one item actually checked - plausible, since
# they were all generated by the same automated SynapseML pipeline (see
# the arXiv paper above), but not verified one by one. If a search or
# resolve still fails for a particular book, check the actual HTTP status
# and response body in FreeRadio's log (see _fetch()'s error handling)
# before assuming this note is still the full picture.
#
# NOTE ON PASTED ARCHIVE.ORG BOOK LINKS: a bare archive.org "details" URL
# looks identical whether it's a LibriVox recording or a Project Gutenberg
# audiobook - librivox.looks_like_book_url() matches either one. So that a
# pasted Gutenberg link doesn't get silently mis-resolved as a LibriVox
# book (or vice versa), get_book_by_url() below checks the resolved
# item's actual collection membership before accepting it (see
# _resolve_book_by_identifier()) rather than accepting any archive.org
# details URL unconditionally the way librivox.get_book_by_url() does.
# radioDialog.py's _on_getem_search() relies on exactly this: it tries
# this module's get_book_by_url() first for any archive.org-shaped
# pasted link, and only falls back to librivox.get_book_by_url() if this
# one rejects the item (or the gutenberg source is disabled) - see the
# comment above its is_gutenberg_url/is_librivox_url handling.

