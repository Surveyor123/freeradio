def resolve_media(book, session=None):
	"""Fills in *book*.chapters with every audio file found for it.
	*session* is accepted but unused - kept only so radioDialog.py can call
	this the same way it calls getem.resolve_media()/librivox.resolve_media(),
	with no source-specific branching. Returns (book, error_message)."""
	if not book.archive_id:
		return book, _("This book has no archive.org item to read audio files from.")
	return _resolve_via_archive_org(book)


def looks_like_book_url(text):
	"""Whether *text* looks like an archive.org book link. See the module
	docstring's note on why radioDialog.py doesn't currently wire this in
	- kept for API compatibility with getem.py/librivox.py and for any
	future caller that disambiguates sources itself."""
	return bool(ARCHIVE_DETAILS_URL_RE.match((text or "").strip()))


def get_book_by_url(url):
	"""Resolves a book directly from an archive.org "details" URL, but
	only if that item actually carries this collection's tag (COLLECTION)
	- unlike librivox.get_book_by_url(), which accepts any archive.org
	details URL unconditionally, this checks the resolved item's own
	metadata first so a LibriVox link pasted here doesn't get silently
	(mis)claimed as a Gutenberg audiobook. Returns (book_or_None,
	error_message)."""
	match = ARCHIVE_DETAILS_URL_RE.match((url or "").strip())
	if not match:
		return None, _("This doesn't look like an archive.org book link.")
	return _resolve_book_by_identifier(match.group(1))


def _resolve_book_by_identifier(identifier):
	url = ARCHIVE_METADATA_URL + urllib.parse.quote(identifier, safe="")
	try:
		response_text = _fetch(url, timeout=REQUEST_TIMEOUT)
	except Exception as e:
		return None, str(e)

	try:
		data = json.loads(response_text)
	except ValueError as e:
		return None, str(e)

	meta = data.get("metadata") or {}
	if not meta or not meta.get("identifier"):
		return None, _("Could not find a book at this address on archive.org.")

	collections = meta.get("collection")
	if isinstance(collections, str):
		collections = [collections]
	collections = [str(c).strip().lower() for c in (collections or [])]
	if collections and COLLECTION.lower() not in collections:
		return None, _("This archive.org item isn't part of the Project Gutenberg Open Audiobook Collection.")

	book = _parse_archive_doc({
		"identifier": identifier,
		"title": meta.get("title"),
		"creator": meta.get("creator"),
		"language": meta.get("language"),
		"description": meta.get("description"),
		"tts-voice": meta.get("tts-voice"),
	})
	return _chapters_from_metadata(book, data)


def _chapters_from_metadata(book, data):
	"""Fills in *book*.chapters from an already-fetched archive.org
	metadata *data* response. Tries each label in
	_AUDIO_FORMAT_CANDIDATES in turn (see the module docstring); if none
	of them match anything, falls back to every file that simply has a
	".mp3" extension, so an unexpected/unverified format label still
	finds the audio instead of coming up empty. Shared by
	_resolve_via_archive_org() and _resolve_book_by_identifier(), same
	split as librivox.py's equivalent. Returns (book, error_message)."""
	files = data.get("files") or []
	server = data.get("server") or data.get("d1") or ""
	item_dir = data.get("dir") or ""

	def _file_url(name):
		if server and item_dir:
			return "https://%s%s/%s" % (server, item_dir, urllib.parse.quote(name))
		return ARCHIVE_DOWNLOAD_BASE + urllib.parse.quote(book.archive_id, safe="") + "/" + urllib.parse.quote(name)

	def _track_key(f):
		track = (f.get("track") or "").split("/")[0].strip()
		try:
			return (0, int(track))
		except (TypeError, ValueError):
			return (1, f.get("name") or "")

	mp3_files = []
	for candidate in _AUDIO_FORMAT_CANDIDATES:
		mp3_files = [f for f in files if isinstance(f, dict) and (f.get("format") or "") == candidate]
		if mp3_files:
			break
	if not mp3_files:
		# None of the known-guess labels matched - fall back to picking
		# every file that merely looks like an MP3 by extension, rather
		# than reporting no audio at all. See the module docstring.
		mp3_files = [
			f for f in files
			if isinstance(f, dict) and (f.get("name") or "").lower().endswith(".mp3")
		]
	mp3_files.sort(key=_track_key)

	chapters = []
	for f in mp3_files:
		name = f.get("name") or ""
		if not name:
			continue
		title = (f.get("title") or "").strip() or os.path.splitext(os.path.basename(name))[0]
		chapters.append({"title": title, "url": _file_url(name)})

	if not chapters:
		return book, _("No playable audio file was found for this book on archive.org.")

	book.chapters = chapters
	return book, None


def _resolve_via_archive_org(book):
	url = ARCHIVE_METADATA_URL + urllib.parse.quote(book.archive_id, safe="")
	try:
		response_text = _fetch(url, timeout=REQUEST_TIMEOUT)
	except Exception as e:
		return book, str(e)

	try:
		data = json.loads(response_text)
	except ValueError as e:
		return book, str(e)

	return _chapters_from_metadata(book, data)


