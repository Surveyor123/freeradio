# Library persistence - same shape as getem.GetemLibrary/
# librivox.LibrivoxLibrary.
# --------------------------------------------------------------------- #

class GutenbergLibrary:
	"""The user's saved Project Gutenberg Open Audiobook Collection
	titles. Persisted separately from GETEM's and LibriVox's libraries
	(its own JSON file) - RadioDialog._merged_library_books() is what
	combines all three into one shelf for display."""

	def __init__(self):
		self._books = []
		self._load()

	def _get_path(self):
		return os.path.join(globalVars.appArgs.configPath, "freeradio_gutenberg_audiobooks_library.json")

	def _load(self):
		path = self._get_path()
		if not os.path.exists(path):
			return
		try:
			with open(path, "r", encoding="utf-8") as f:
				data = json.load(f)
			self._books = [GutenbergAudiobook.from_dict(item) for item in data if isinstance(item, dict)]
		except Exception as e:
			log.warning("FreeRadio Gutenberg Audiobooks: failed to load library: %s", e)

	def save(self):
		try:
			path = self._get_path()
			tmp_path = path + ".tmp"
			with open(tmp_path, "w", encoding="utf-8") as f:
				json.dump([b.to_library_dict() for b in self._books], f, ensure_ascii=False, indent=4)
			os.replace(tmp_path, path)
		except Exception as e:
			log.warning("FreeRadio Gutenberg Audiobooks: failed to save library: %s", e)

	def get_books(self):
		return list(self._books)

	def get_book_by_key(self, key):
		for book in self._books:
			if book.identity_key() == key:
				return book
		return None

	def is_in_library(self, book):
		return self.get_book_by_key(book.identity_key()) is not None

	def add_book(self, book):
		if self.is_in_library(book):
			return False
		self._books.append(book)
		self.save()
		return True

	def remove_book(self, book):
		existing = self.get_book_by_key(book.identity_key())
		if not existing:
			return False
		self._books.remove(existing)
		self.save()
		return True

	def mark_progress(self, book, chapter_index):
		existing = self.get_book_by_key(book.identity_key())
		if not existing:
			return
		existing.last_chapter_index = chapter_index
		self.save()
