def _fetch(url, timeout=REQUEST_TIMEOUT):
	headers = {
		"User-Agent": USER_AGENT,
		"Accept": "application/json, application/xml;q=0.9, text/xml;q=0.8, */*;q=0.5",
	}
	req = urllib.request.Request(url, headers=headers)
	try:
		with urllib.request.urlopen(req, timeout=timeout) as resp:
			raw = resp.read()
			charset = resp.headers.get_content_charset() or "utf-8"
			return raw.decode(charset, errors="replace")
	except urllib.error.HTTPError as e:
		# Surface the server's own response body, not just the bare status
		# code - see librivox._fetch()'s identical comment for why this
		# level of detail is what actually gets a real failure diagnosed
		# rather than re-guessed.
		try:
			body = e.read().decode("utf-8", errors="replace")[:300].strip()
		except Exception:
			body = ""
		detail = (" | response body: %s" % body) if body else " | (no response body)"
		raise RuntimeError("HTTP %s for %s%s" % (e.code, url, detail)) from e


def _first_str(value):
	"""archive.org's advancedsearch.php returns a field as either a bare
	string or a list of strings depending on the item - normalizes either
	shape to a single string, taking the first entry for a list."""
	if isinstance(value, list):
		return str(value[0]) if value else ""
	return str(value) if value is not None else ""


def _strip_html(text):
	return re.sub(r"<[^>]+>", "", text or "").strip()


def _parse_archive_doc(doc):
	"""Turns one 'doc' entry from archive.org's advancedsearch.php search
	response into a GutenbergAudiobook, with book.archive_id set so
	resolve_media() knows to fetch its file listing from archive.org's
	metadata API (see _resolve_via_archive_org())."""
	identifier = _first_str(doc.get("identifier")).strip()
	title = _first_str(doc.get("title")).strip() or _("Unknown")

	creators = doc.get("creator")
	if isinstance(creators, list):
		author = ", ".join(c.strip() for c in (str(x) for x in creators) if c.strip())
	else:
		author = _first_str(creators).strip()

	language = _first_str(doc.get("language")).strip()
	description = _strip_html(_first_str(doc.get("description")))
	tts_voice = _first_str(doc.get("tts-voice")).strip()

	detail_url = ARCHIVE_DETAILS_BASE + identifier
	book = GutenbergAudiobook(
		title=title, detail_url=detail_url, author=author,
		description=description, language=language, tts_voice=tts_voice,
	)
	book.archive_id = identifier
	# Translators: shown in parentheses next to a book's title/author,
	# e.g. "(AI narration, English)" - tells the user upfront that this
	# is a synthetic voice, same information carried by book.narrator,
	# repeated here since format_label is what actually shows in the
	# compact search-results/library list rows (see
	# RadioDialog._format_getem_result_label()).
	if language:
		book.format_label = _("AI narration, %s") % language
	else:
		book.format_label = _("AI narration")
	return book


def search_gutenberg_audiobooks(query, limit=RESULTS_PER_QUERY):
	"""Searches for Project Gutenberg Open Audiobook Collection titles
	matching *query*, against archive.org's "gutenberg-audiobooks"
	collection tag - see the module docstring for why. Matches against
	title OR creator (author) in a single request, the same as
	librivox.search_librivox(). Returns (list_of_GutenbergAudiobook,
	error_message)."""
	query = (query or "").strip()
	if not query:
		return [], _("Please enter a search term.")

	phrase = query.replace('"', "")
	search_q = 'collection:(%s) AND (title:("%s") OR creator:("%s"))' % (COLLECTION, phrase, phrase)
	params = [
		("q", search_q),
		("fl[]", "identifier"),
		("fl[]", "title"),
		("fl[]", "creator"),
		("fl[]", "language"),
		("fl[]", "description"),
		("fl[]", "tts-voice"),
		("rows", str(limit)),
		("page", "1"),
		("output", "json"),
	]
	url = "%s?%s" % (ARCHIVE_ADVANCED_SEARCH_URL, urllib.parse.urlencode(params))
	try:
		response_text = _fetch(url, timeout=SEARCH_TIMEOUT)
	except Exception as e:
		log.warning("FreeRadio Gutenberg Audiobooks: archive.org search failed: %s", e)
		return [], str(e)

	try:
		data = json.loads(response_text)
	except ValueError as e:
		log.warning("FreeRadio Gutenberg Audiobooks: could not parse archive.org search response: %s", e)
		return [], str(e)

	docs = (((data or {}).get("response") or {}).get("docs")) or []
	books = []
	for doc in docs:
		try:
			books.append(_parse_archive_doc(doc))
		except Exception as e:
			log.warning("FreeRadio Gutenberg Audiobooks: could not parse one archive.org result: %s", e)

	return books, None


# --------------------------------------------------------------------- #
# Book model - see the module docstring for why this mirrors
# LibrivoxBook/GetemBook.
# --------------------------------------------------------------------- #

class GutenbergAudiobook:
	"""A single Project Gutenberg Open Audiobook Collection title.
	Attribute- and method-compatible with getem.GetemBook/
	librivox.LibrivoxBook so radioDialog.py's generic Audio Books tab code
	works unmodified against this source too - see
	RadioDialog._audiobook_module_for()/_audiobook_library_for()."""

	def __init__(self, title, detail_url, author="", format_label="",
			description="", language="", archive_id="", tts_voice=""):
		self.title = title or _("Unknown")
		self.detail_url = detail_url
		self.author = author
		# Every book in this collection is narrated the same way (see the
		# module docstring), so this is a fixed, honest label rather than
		# blank - unlike LibriVox, which credits a different human reader
		# per chapter and so has nothing fixed to put here. When the
		# item's specific Azure voice name is known (tts_voice, e.g.
		# "SteffanNeural"), it's named directly rather than staying
		# generic - genuinely useful for a returning listener who's
		# learned they like (or don't like) a particular voice.
		self.tts_voice = tts_voice
		if tts_voice:
			# Translators: %s = the specific AI voice name, e.g. "SteffanNeural"
			self.narrator = _("AI-generated narration (Microsoft neural text-to-speech, %s voice)") % tts_voice
		else:
			self.narrator = _AI_NARRATOR_LABEL
		self.format_label = format_label
		self.description = description
		# Project Gutenberg has no separate "publisher" concept distinct
		# from Project Gutenberg itself; kept empty for attribute
		# compatibility with GetemBook/LibrivoxBook (used by
		# _format_getem_details()).
		self.publisher = ""
		self.language = language
		# archive.org item identifier - resolve_media() uses this to
		# fetch the file listing from archive.org's metadata API.
		self.archive_id = archive_id
		# Populated lazily by resolve_media(): [{"title": str, "url": str}, ...].
		# Almost always a single entry (one MP3 per book), but kept as a
		# list - same shape as GetemBook/LibrivoxBook - in case a very
		# long title was split into more than one file.
		self.chapters = []
		self.last_chapter_index = 0
		self.audio_profile = None

	def identity_key(self):
		return self.detail_url

	def to_dict(self):
		"""Same station-like dict shape as getem.GetemBook.to_dict()/
		librivox.LibrivoxBook.to_dict() - see either's docstring for the
		full rationale, in particular why "getem_detail_url" is reused
		verbatim rather than inventing a third field name: several other
		files (radioPlayer.py's resume/seek/speed handling, __init__.py's
		own-session "resume last station" rebuild) key off that exact
		name regardless of which of the three sources a book actually
		came from."""
		return {
			"name": self.title,
			"url": "",
			"url_resolved": "",
			"stationuuid": "gutenberg-audiobook-" + str(uuid.uuid5(uuid.NAMESPACE_URL, self.detail_url)),
			"countrycode": "",
			"tags": "podcast,audiobook",
			"media_kind": "audiobook",
			"getem_detail_url": self.detail_url,
			"author": self.author,
			"narrator": self.narrator,
			"publisher": self.publisher,
			"audiobook_format": self.format_label,
			"audiobook_chapter_count": len(self.chapters),
			"description": self.description,
			# Translators: shown as this book's source in the station-details
			# dialog and the Audio Books tab - kept distinct from bare
			# "LibriVox"/"GETEM" (see RadioDialog._audiobook_source_label_for())
			# since this collection is machine-narrated rather than a
			# volunteer-read or library-hosted human-narrated catalog.
			"audiobook_source": _("Project Gutenberg (AI narration)"),
		}

	def to_library_dict(self):
		return {
			"title": self.title,
			"author": self.author,
			"format_label": self.format_label,
			"description": self.description,
			"language": self.language,
			"archive_id": self.archive_id,
			"detail_url": self.detail_url,
			"tts_voice": self.tts_voice,
			"chapters": self.chapters,
			"last_chapter_index": self.last_chapter_index,
			"audio_profile": self.audio_profile,
		}

	@classmethod
	def from_dict(cls, data):
		book = cls(
			title=data.get("title", ""),
			detail_url=data.get("detail_url", ""),
			author=data.get("author", ""),
			format_label=data.get("format_label", ""),
			description=data.get("description", ""),
			language=data.get("language", ""),
			archive_id=data.get("archive_id", ""),
			tts_voice=data.get("tts_voice", ""),
		)
		book.chapters = data.get("chapters", []) or []
		book.last_chapter_index = data.get("last_chapter_index", 0) or 0
		book.audio_profile = data.get("audio_profile") or None
		return book


