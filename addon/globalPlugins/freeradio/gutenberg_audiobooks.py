# The archive.org collection tag every book in the collection carries -
# see the module docstring's "CONFIRMED AGAINST A REAL ITEM" section.
COLLECTION = "gutenberg-audiobooks"
ARCHIVE_ADVANCED_SEARCH_URL = "https://archive.org/advancedsearch.php"
ARCHIVE_METADATA_URL = "https://archive.org/metadata/"
ARCHIVE_DOWNLOAD_BASE = "https://archive.org/download/"
ARCHIVE_DETAILS_BASE = "https://archive.org/details/"
ARCHIVE_DETAILS_URL_RE = re.compile(
	r"^https?://(?:www\.)?archive\.org/details/([A-Za-z0-9._-]+)", re.IGNORECASE)
USER_AGENT = "FreeRadio-NVDA/1.0"
REQUEST_TIMEOUT = 15
SEARCH_TIMEOUT = 20
RESULTS_PER_QUERY = 100

# Tried in order against each item's file listing - "MP3" is the
# confirmed label (see the module docstring); the other two are kept as
# fallbacks in case some items in this ~5000-title collection were
# produced differently.
_AUDIO_FORMAT_CANDIDATES = ("MP3", "VBR MP3", "64Kbps MP3")

# Shown as this book's narrator (see GutenbergAudiobook.__init__) instead
# of leaving the field blank the way LibriVox does (which credits a
# different human reader per chapter) - every book in this collection
# shares the same kind of narration, so one fixed, honest label is more
# useful here than an empty field.
_AI_NARRATOR_LABEL = _("AI-generated narration (Microsoft neural text-to-speech)")


